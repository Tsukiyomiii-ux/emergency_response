String formatTime(DateTime t, {bool seconds = false}) {
  final h12 = t.hour % 12 == 0 ? 12 : t.hour % 12;
  final mm = t.minute.toString().padLeft(2, '0');
  final ss = seconds ? ':${t.second.toString().padLeft(2, '0')}' : '';
  return '$h12:$mm$ss ${t.hour < 12 ? 'AM' : 'PM'}';
}