class Ticket {
  Ticket({
    required this.id,
    required this.type,
    required this.detail,
    required this.location,
    required this.reportedAt,
    this.note = '',
    this.status = TicketStatus.reported,
    this.responder,
    this.routedTo, // NEW: Algorithm's target
    Map<TicketStatus, DateTime>? times,
  }) : times = times ?? {TicketStatus.reported: reportedAt};

  final String id;
  final TicketType type;
  final String detail;
  final String location;
  final String note;
  final DateTime reportedAt;
  
  TicketStatus status;
  String? responder;
  String? routedTo;
  
  final Map<TicketStatus, DateTime> times;

  bool get isNew => status == TicketStatus.reported;
  PriorityLevel get basePriority => kBasePriorities[detail] ?? PriorityLevel.low;
  
  PriorityLevel get currentPriority {
    final base = basePriority;
    if (base == PriorityLevel.high) return PriorityLevel.high;

    final elapsedMins = DateTime.now().difference(reportedAt).inMinutes;

    if (base == PriorityLevel.medium) {
      return elapsedMins >= 5 ? PriorityLevel.high : PriorityLevel.medium;
    }

    if (elapsedMins >= 10) return PriorityLevel.high;
    if (elapsedMins >= 5) return PriorityLevel.medium;

    return PriorityLevel.low;
  }
  
  String get priorityLabel => currentPriority.label;

  Map<String, dynamic> toMap() {
    return {
      'type': type.name,
      'detail': detail,
      'location': location,
      'note': note,
      'reportedAt': reportedAt.toIso8601String(),
      'status': status.name,
      'responder': responder,
      'routedTo': routedTo,
      'times': times.map((k, v) => MapEntry(k.name, v.toIso8601String())),
    };
  }

  factory Ticket.fromFirestore(DocumentSnapshot doc) {
    final data = doc.data() as Map<String, dynamic>? ?? {};
    final timesMap = data['times'] as Map<String, dynamic>? ?? {};
    return Ticket(
      id: doc.id,
      type: TicketType.values.byName(data['type'] ?? 'medical'),
      detail: data['detail'] ?? '',
      location: data['location'] ?? '',
      note: data['note'] ?? '',
      reportedAt: DateTime.tryParse(data['reportedAt']?.toString() ?? '') ?? DateTime.now(),
      status: TicketStatus.values.byName(data['status'] ?? 'reported'),
      responder: data['responder'],
      routedTo: data['routedTo'],
      times: timesMap.map((k, v) => MapEntry(TicketStatus.values.byName(k), DateTime.tryParse(v.toString()) ?? DateTime.now())),
    );
  }
}

